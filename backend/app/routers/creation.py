@router.get("/artwork/{artwork_id}/image")
def artwork_image(project_id: str, artwork_id: str, request: Request, download: bool = False):
    with Session(request.app.state.engine) as db:
        project_check(db, project_id)
        row = artwork_for(db, project_id, artwork_id)
        path = request.app.state.config.asset_dir / "artwork" / f"{row.digest}.png"
        if not path.is_file():
            raise HTTPException(404, "Artwork file is missing. Restore it from your backup.")
        return FileResponse(
            path,
            media_type="image/png",
            filename=f"variance-{row.id[:8]}.png" if download else None,
        )


@router.patch("/artwork/{artwork_id}", response_model=Artwork)
def review_artwork(project_id: str, artwork_id: str, payload: ArtworkReview, request: Request):
    with Session(request.app.state.engine) as db:
        db.connection().exec_driver_sql("BEGIN IMMEDIATE")
        project_check(db, project_id, write=True)
        row = artwork_for(db, project_id, artwork_id)
        if row.revision != payload.revision:
            raise HTTPException(409, "This review changed in another tab. Reload before saving.")
        row.decision, row.review_note = payload.decision, payload.review_note
        row.revision += 1
        db.add(row)
        db.flush()
        refresh_batch(db, batch_for(db, project_id, row.batch_id))
        db.commit()
        db.refresh(row)
        return row
