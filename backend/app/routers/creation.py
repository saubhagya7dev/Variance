def prompt_for(db: Session, project_id: str, prompt_id: str):
    row = db.get(PromptVersion, prompt_id)
    if not row or row.project_id != project_id:
        raise HTTPException(404, "Prompt version not found.")
    return row


def batch_for(db: Session, project_id: str, batch_id: str):
    row = db.get(CreationBatch, batch_id)
    if not row or row.project_id != project_id:
        raise HTTPException(404, "Image batch not found.")
    return row


@router.post("/prompts/preview")
def preview(project_id: str, payload: Direction, request: Request):
    with Session(request.app.state.engine) as db:
        project = project_check(db, project_id, write=True)
        context = capture_context(db, project)
        return {
            "context_hash": context_hash(context),
            "context": context,
            "prompt_text": compose_prompt(payload, context),
        }


@router.post("/prompts")
def save_prompt(project_id: str, payload: PromptSave, request: Request):
    with Session(request.app.state.engine) as db:
        db.connection().exec_driver_sql("BEGIN IMMEDIATE")
        project = project_check(db, project_id, write=True)
        context = capture_context(db, project)
        if context_hash(context) != payload.context_hash:
            raise HTTPException(
                409,
                "References, notes, or research changed. Assemble the prompt again and review before saving.",
            )
        version = (
            db.exec(
                select(func.max(PromptVersion.version)).where(
                    PromptVersion.project_id == project_id
                )
            ).one()
            or 0
        ) + 1
        row = PromptVersion(
            project_id=project_id,
            version=version,
            direction_json=payload.direction.model_dump_json(),
            context_json=json.dumps(context),
            prompt_text=payload.prompt_text,
        )
        db.add(row)
        db.commit()
        db.refresh(row)
        return prompt_view(row)


