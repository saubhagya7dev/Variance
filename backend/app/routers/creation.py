@router.get("/prompts/{prompt_id}/pack")
def export_pack(project_id: str, prompt_id: str, request: Request):
    with Session(request.app.state.engine) as db:
        project_check(db, project_id)
        row = prompt_for(db, project_id, prompt_id)
        payload = prompt_view(row)
    refs = payload["context"]["references"]
    paths = [request.app.state.config.asset_dir / f"{ref['digest']}.png" for ref in refs]
    if any(not path.is_file() for path in paths):
        raise HTTPException(
            409, "A frozen reference file is missing. Restore your image backup before exporting."
        )
    if sum(path.stat().st_size for path in paths) > 64 * 1024 * 1024:
        raise HTTPException(
            413, "Reference pack exceeds 64 MB. Create a new prompt with fewer references."
        )
    output = BytesIO()
    with ZipFile(output, "w", compression=ZIP_DEFLATED) as bundle:
        bundle.writestr("prompt.txt", payload["prompt_text"])
        bundle.writestr("manifest.json", json.dumps(payload, ensure_ascii=False, indent=2))
        bundle.writestr(
            "README.txt",
            "Manual generation pack\nAttach the numbered references in order, paste prompt.txt into your chosen image tool, and import the results into the matching Variance batch.\nNo images were generated by exporting this pack. Check source licences in manifest.json. Research is context to review, not guaranteed fact.\n",
        )
        for i, path in enumerate(paths):
            bundle.write(path, f"references/{i + 1:02d}.png")
    return Response(
        output.getvalue(),
        media_type="application/zip",
        headers={
            "Content-Disposition": f'attachment; filename="variance-{project_id[:8]}-prompt-v{payload["version"]}.zip"'
        },
    )


